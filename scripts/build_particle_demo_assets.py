"""Pack the TouchDesigner stills into sprite sheets for /ParticleMorphingDemo.

Each article that has all four stills in the TD render cache gets one WebP:
the four images side by side, each cropped to the node thumbnail's aspect
(162x176) and scaled to the particle grid, so the page reads one pixel per
particle. The stills are the raw Stable Diffusion frames, so they get the same
lift the finished videos have (brighter, about two thirds the saturation).

    python scripts/build_particle_demo_assets.py [--limit N]   (default: all)

Writes static/images/nodes/particle-demo/<id>.webp and
src/lib/data/particleDemo.generated.ts. Articles missing from the site's
article list are skipped, as are ones without four stills.
"""

import argparse
import hashlib
import json
import re
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / 'Stable_Diffusion_Particles_aiD' / 'Stable_Diffusion_Particles_aiD' / 'render_cache_refstyle'
OUT_DIR = ROOT / 'static' / 'images' / 'nodes' / 'particle-demo'
MANIFEST = ROOT / 'src' / 'lib' / 'data' / 'particleDemo.generated.ts'
ARTICLES = ROOT / 'src' / 'lib' / 'data' / 'articles.generated.ts'

# Particle grid: 192 rows, columns to match the 162x176 thumbnail. Must match
# GRID_COLUMNS / GRID_ROWS in src/lib/particles/morphData.ts.
COLUMNS, ROWS = 177, 192
STILLS = 4
GAMMA = 1.3          # TD grade_level gamma1
SATURATION = 0.65    # the particle feedback in TD washes colour out about this much
QUALITY = 86


def grade(image: Image.Image) -> Image.Image:
    rgb = np.asarray(image.convert('RGB'), dtype=np.float32) / 255.0
    rgb = rgb ** (1.0 / GAMMA)
    luma = rgb @ np.array([0.2126, 0.7152, 0.0722], dtype=np.float32)
    rgb = luma[..., None] + (rgb - luma[..., None]) * SATURATION
    return Image.fromarray((np.clip(rgb, 0, 1) * 255 + 0.5).astype(np.uint8))


def fit(image: Image.Image) -> Image.Image:
    """Centre-crop to the grid's aspect (object-fit: cover), then scale."""
    w, h = image.size
    target = COLUMNS / ROWS
    if w / h > target:
        cw = round(h * target)
        box = ((w - cw) // 2, 0, (w - cw) // 2 + cw, h)
    else:
        ch = round(w / target)
        box = (0, (h - ch) // 2, w, (h - ch) // 2 + ch)
    return image.crop(box).resize((COLUMNS, ROWS), Image.LANCZOS)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--limit', type=int, default=0, help='0 = every article with stills')
    args = parser.parse_args()

    known = set(re.findall(r'"id":\s*"([^"]+)"', ARTICLES.read_text(encoding='utf-8')))
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    sheets: dict[str, str] = {}
    for folder in sorted(p for p in CACHE.iterdir() if p.is_dir()):
        if args.limit and len(sheets) >= args.limit:
            break
        stills = [folder / f'{k}.png' for k in range(STILLS)]
        if folder.name not in known or not all(p.exists() for p in stills):
            continue
        sheet = Image.new('RGB', (COLUMNS * STILLS, ROWS))
        for k, path in enumerate(stills):
            sheet.paste(grade(fit(Image.open(path))), (k * COLUMNS, 0))
        target = OUT_DIR / f'{folder.name}.webp'
        sheet.save(target, 'WEBP', quality=QUALITY, method=6)
        digest = hashlib.sha256(target.read_bytes()).hexdigest()[:8]
        sheets[folder.name] = f'/images/nodes/particle-demo/{folder.name}.webp?v={digest}'

    for stale in OUT_DIR.glob('*.webp'):
        if stale.stem not in sheets:
            stale.unlink()

    body = ',\n'.join(f'\t{json.dumps(k)}: {json.dumps(v)}' for k, v in sheets.items())
    MANIFEST.write_text(
        '// Generated by scripts/build_particle_demo_assets.py -- do not edit by hand.\n'
        '// Article id -> sprite sheet of its four stills for /ParticleMorphingDemo.\n\n'
        f'export const PARTICLE_SHEET_COLUMNS = {COLUMNS};\n'
        f'export const PARTICLE_SHEET_ROWS = {ROWS};\n'
        f'export const PARTICLE_SHEET_STILLS = {STILLS};\n\n'
        f'export const particleSheets: Record<string, string> = {{\n{body}\n}};\n',
        encoding='utf-8',
    )
    total = sum((OUT_DIR / f'{k}.webp').stat().st_size for k in sheets)
    print(f'{len(sheets)} sheets, {total / 1024:.0f} KB total, avg {total / 1024 / max(1, len(sheets)):.1f} KB')


if __name__ == '__main__':
    main()
