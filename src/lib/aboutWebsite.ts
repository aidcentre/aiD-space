export interface ResolvedAboutWebsite {
	title: string;
	paragraphs: string[];
	credits: AboutWebsiteCredit[];
}

/** Studio content where it's filled in, the defaults above where it isn't. */
export function resolveAboutWebsite(settings: Settings | null | undefined): ResolvedAboutWebsite {
	const about: AboutWebsite = settings?.aboutWebsite ?? {};
	const body = about.body?.trim() ? about.body : DEFAULT_BODY;
	const credits = about.credits?.filter((credit) => credit.label || credit.value);

	return {
		title: about.title?.trim() || DEFAULT_TITLE,
		paragraphs: body
			.split(/\n\s*\n/)
			.map((paragraph) => paragraph.trim())
			.filter(Boolean),
		credits: credits?.length ? credits : DEFAULT_CREDITS
	};
}
