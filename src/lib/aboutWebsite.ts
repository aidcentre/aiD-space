import type { AboutWebsite, AboutWebsiteCredit, Settings } from '$lib/sanity/types';

/**
 * The collapsible "About this website" section at the bottom of the What is aiD
 * page. Its text comes from Settings → About this website in the studio; the
 * defaults below fill any field that is left empty there.
 */

/** Slug of the page the section is rendered on. */
export const ABOUT_WEBSITE_PAGE_SLUG = 'what-is-aid';

/** Element id of the section, and the hash that opens it. */
export const ABOUT_WEBSITE_ID = 'about-this-website';

export const ABOUT_WEBSITE_HREF = `/${ABOUT_WEBSITE_PAGE_SLUG}#${ABOUT_WEBSITE_ID}`;

/**
 * Fired by links that should open the section. A link to the hash covers
 * arriving from another page, but clicking it again on the same page doesn't
 * change the URL, so the event re-opens the section if it was collapsed.
 */
export const ABOUT_WEBSITE_REVEAL_EVENT = 'aid:reveal-about-website';

export function revealAboutWebsite() {
	window.dispatchEvent(new Event(ABOUT_WEBSITE_REVEAL_EVENT));
}

const DEFAULT_TITLE = 'About this website';

const DEFAULT_BODY = `This website is the result of months of design deliberation and close collaboration between designers, developers and researchers. Every page was designed and built by hand, with one goal in mind: to give aiD a home online that is genuinely useful and a pleasure to explore.

The moving thumbnails on the nodes of the front page were generated by AI models running locally, guided by the people who shaped the site's visual direction. Behind the scenes, the site is connected to aiD's Microsoft Teams SharePoint, so articles stay up to date automatically as new work is published.

Search runs on a retrieval-augmented (RAG) engine on our own backend. Rather than simply matching the words you type, it understands what you are looking for and returns only what is truly relevant — a far more capable search than traditional keyword matching.

Above all, the site is a collaboration between people and AI: human judgement and craft where they matter most, and AI where it extends what a small team can achieve. We hope the result is both useful and beautiful, and a small demonstration of what aiD is all about.`;

